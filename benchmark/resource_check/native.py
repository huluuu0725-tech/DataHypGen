"""One native-proposal evaluation path for both experiment suites."""

import copy
import re

from benchmark.resource_check.checker import anchor_members
from benchmark.resource_check.semantics import validate_extraction


def retrieval_requirement(requirement):
    result = {
        "dataset_name": requirement["name"],
        "canonical_requirement_name": requirement["query"],
        "aliases": [requirement["name"]],
        "semantic_requirement_text": " ".join(item["text"] for item in requirement["constraints"]),
    }
    identifier = requirement["identifier"]
    platform = requirement["platform"].casefold()
    if identifier:
        result["aliases"].insert(0, identifier)
        if platform in {"gee", "google earth engine"}:
            result["data_path"] = "GEE:" + identifier
        elif identifier.startswith(("https://", "http://")):
            result["data_path"] = identifier
        elif platform in {"nasa cmr", "microsoft planetary computer", "aws earth search"}:
            source = {"nasa cmr": "NASA_CMR", "microsoft planetary computer": "PLANETARY_COMPUTER",
                      "aws earth search": "EARTH_SEARCH"}[platform]
            result["source_metadata"] = {"source": source, "id": identifier}
    return result


def tokens(text):
    return set(re.findall(r"[a-z0-9]+", text.casefold()))


def tool_candidates(checker, requirement, limit):
    query = tokens(requirement["query"] + " " + requirement["name"])
    declared = tokens(requirement["declared_tool"])
    ranked = []
    for name, entry in checker.functions.items():
        identity = tokens(" ".join(str(entry.get(key, "")) for key in ("function_name", "module", "package")))
        if declared and not declared.issubset(identity):
            continue
        # Rank the compact index first; detail files are large and loaded only for finalists.
        search_text = " ".join(str(entry.get(key, "")) for key in
                               ("function_name", "raw_description", "task_type", "signature"))
        overlap = query & tokens(search_text)
        if overlap or declared:
            ranked.append((len(overlap), name, entry))
    ranked.sort(key=lambda item: (-item[0], item[1]))
    return [checker.details.merge(item[2], checker.details.get(item[2])) for item in ranked[:limit]]


async def evaluate_native(extractions, task, *, checker, semantics, tool_candidate_limit):
    anchors = []
    for index, member in enumerate(anchor_members(task), 1):
        anchors.append(await checker.check_dataset(member, f"anchor_{index}", anchor=True))
    applications = []
    for extracted in extractions:
        rows = []
        for requirement in extracted["extraction"]["requirements"]:
            row = {"requirement_id": requirement["id"], "kind": requirement["kind"],
                   "dependency": requirement["dependency"], "condition": requirement["condition"]}
            if requirement["kind"] == "derived":
                row.update(status="derived", reason="Generated by the proposal; not an external resource")
            elif requirement["kind"] == "dataset":
                binding = await checker.check_dataset(
                    retrieval_requirement(requirement), requirement["id"],
                    mandatory=requirement["dependency"] in {"required", "unspecified"},
                )
                row["binding"] = binding
                if binding["bind_status"] == "bindable":
                    evidence = dict(binding.get("resource_evidence", {}))
                    if binding.get("dataset_id"):
                        evidence["catalog"] = checker.catalog_evidence(
                            retrieval_requirement(requirement), binding["dataset_id"],
                        )
                    row["resource_evidence"] = evidence
                    verdict = await semantics.verify(requirement, evidence)
                    row.update(verdict)
                else:
                    row.update(status="unverified", reason="No accessible matching dataset verified", quotes=[])
            else:
                candidates = tool_candidates(checker, requirement, tool_candidate_limit)
                row.update(status="unverified", reason="No retrieved implementation proved all requirements", quotes=[])
                row["candidate_verdicts"] = []
                for candidate in candidates:
                    verdict = await semantics.verify(requirement, candidate)
                    row["candidate_verdicts"].append({"function_name": candidate["function_name"], **verdict})
                    if verdict["status"] == "satisfied":
                        row.update(verdict)
                        row["matched_function"] = candidate["function_name"]
                        break
                row["candidates"] = candidates
                row["verification_scope"] = "documented capability; no installation or experiment execution"
            rows.append(row)
        mandatory = [row for row in rows if row["dependency"] in {"required", "unspecified"}
                     and row["kind"] != "derived"]
        gaps = [row for row in mandatory if row["status"] != "satisfied"]
        ambiguous = bool(extracted["extraction"]["ambiguities"]) or any(
            row["dependency"] == "unspecified" for row in rows
        )
        conditional = any(row["dependency"] == "conditional" for row in rows)
        anchors_pass = all(row["bind_status"] == "bindable" for row in anchors)
        passed = bool(mandatory) and anchors_pass and not gaps and not ambiguous
        applications.append({
            "idea_id": extracted["proposal_id"],
            "source_artifact": extracted["source_artifact"],
            "resource_requirements": copy.deepcopy(extracted["extraction"]),
            "resource_check": {
                "requirements": rows,
                "execution_contract": {
                    "resource_check_passed": passed,
                    "resource_check_status": ("conditional" if conditional else "verified") if passed else "unverified",
                    "data_access_manifest": copy.deepcopy(anchors),
                    "should_terminate": False,
                },
            },
        })
    return applications


async def extract_bundle(bundle, request, semantics):
    rows = []
    for proposal in bundle["proposals"]:
        text = proposal["native_proposal"]
        if proposal["native_format"] != "markdown":
            raise ValueError("This evaluator accepts native Markdown proposals")
        extraction = await semantics.extract(text, request["task_prompt"])
        validate_extraction(extraction, text, request["task_prompt"])
        rows.append({"proposal_id": proposal["source_artifact"], "source_artifact": proposal["source_artifact"],
                     "extraction": extraction})
    if not rows:
        raise ValueError("Cannot evaluate an empty proposal bundle")
    return rows
